"""Convenience wrapper chaining packaging/seeker.spec's PyInstaller
build with packaging/dmg_settings.py's dmgbuild step — the two
commands documented in docs/packaging.md, run back to back:

    uv run python packaging/build_dmg.py

Produces dist/Seeker.app (via PyInstaller) and the image (via dmgbuild)
in one call: dist/Seeker.dmg built from an arm64 interpreter,
dist/Seeker-Intel.dmg from an x86_64 one (the spec targets the
interpreter's architecture). Between the two steps bundle_check.py
fails the build when a binary lacks that architecture or needs a newer
macOS than the bundle declares. Either step can still be run on its own with
the commands in docs/packaging.md — this is a convenience, not a
replacement.
"""

import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

# Run as a script, so its own folder is on the path.
import bundle_check
import bundle_info

PROJECT_ROOT = Path(__file__).resolve().parent.parent
PACKAGING_DIR = PROJECT_ROOT / "packaging"
DIST_DIR = PROJECT_ROOT / "dist"
APP_PATH = DIST_DIR / "Seeker.app"
BUILD_INFO_PATH = PROJECT_ROOT / "src" / "seeker" / "_build_info_generated.py"


def _write_build_info() -> None:
    """Writes this build's real identity to a gitignored generated
    module, so two builds made hours apart from the same source tree
    stop being indistinguishable from inside the running app. The
    tracked `_build_info.py` fallback is never touched by this function
    — see .gitignore's own comment on this module (HISTORY §81, §83).
    """
    git_sha = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"],
        check=True, cwd=PROJECT_ROOT, capture_output=True, text=True,
    ).stdout.strip()
    git_describe = subprocess.run(
        ["git", "describe", "--dirty", "--always"],
        check=True, cwd=PROJECT_ROOT, capture_output=True, text=True,
    ).stdout.strip()
    built_at = datetime.now(timezone.utc).isoformat()

    BUILD_INFO_PATH.write_text(
        '"""Generated by packaging/build_dmg.py — see that file\'s own '
        '_write_build_info() docstring. Not hand-edited; a real build '
        'overwrites this every time."""\n\n'
        f'GIT_SHA = {git_sha!r}\n'
        f'GIT_DESCRIBE = {git_describe!r}\n'
        f'BUILT_AT = {built_at!r}\n',
        encoding="utf-8",
    )
    print(f"Wrote {BUILD_INFO_PATH} ({git_describe}, {built_at})")


def main() -> None:
    if sys.platform != "darwin":
        raise SystemExit(
            "packaging/build_dmg.py only makes sense on macOS — "
            "dmgbuild and .app bundling are both darwin-only."
        )

    _write_build_info()
    try:
        _build()
    finally:
        # Only the frozen build reads it; left behind, `uv build --wheel`
        # would pack it.
        BUILD_INFO_PATH.unlink(missing_ok=True)


def _build() -> None:
    # Not module-level: this file is imported on platforms with no
    # supported target architecture.
    architecture = bundle_info.target_architecture()
    dmg_path = DIST_DIR / bundle_check.dmg_name(architecture)
    subprocess.run(
        [
            sys.executable, "-m", "PyInstaller",
            "--noconfirm", "--clean",
            str(PACKAGING_DIR / "seeker.spec"),
        ],
        check=True,
        cwd=PROJECT_ROOT,
    )

    if not APP_PATH.is_dir():
        raise SystemExit(
            f"Expected {APP_PATH} after the PyInstaller build but it "
            "doesn't exist — check seeker.spec's BUNDLE() step."
        )

    problems = bundle_check.check_bundle(
        APP_PATH, architecture, bundle_info.MINIMUM_SYSTEM_VERSION,
    )
    if problems:
        raise SystemExit(
            f"{APP_PATH} failed the {architecture} check:\n  "
            + "\n  ".join(problems)
        )
    print(f"{APP_PATH}: every Mach-O is {architecture}, minos <= "
          f"{bundle_info.MINIMUM_SYSTEM_VERSION}")

    if dmg_path.exists():
        dmg_path.unlink()

    subprocess.run(
        [
            sys.executable, "-m", "dmgbuild",
            "-s", str(PACKAGING_DIR / "dmg_settings.py"),
            "-D", f"app={APP_PATH}",
            "Seeker",
            str(dmg_path),
        ],
        check=True,
        cwd=PROJECT_ROOT,
    )

    print(f"Built {dmg_path}")


if __name__ == "__main__":
    main()
